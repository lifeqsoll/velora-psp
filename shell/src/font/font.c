static const unsigned char *find_extra(unsigned cp)
{
    size_t i;
    for (i = 0; i < sizeof(EXTRA) / sizeof(EXTRA[0]); ++i) {
        if (EXTRA[i].cp == cp)
            return EXTRA[i].rows;
    }
    return NULL;
}

/* Classic ASCII dump above is LSB=left; our plotter and Cyrillic use MSB=left. */
static unsigned char bitrev8(unsigned char b)
{
    b = (unsigned char)(((b & 0xF0) >> 4) | ((b & 0x0F) << 4));
    b = (unsigned char)(((b & 0xCC) >> 2) | ((b & 0x33) << 2));
    b = (unsigned char)(((b & 0xAA) >> 1) | ((b & 0x55) << 1));
    return b;
}

const unsigned char *shell_font_glyph(unsigned cp)
{
    static unsigned char ascii_msb[8];
    const unsigned char *g;
    int i;
    if (cp >= 32 && cp <= 126) {
        g = ASCII[cp - 32];
        for (i = 0; i < 8; ++i)
            ascii_msb[i] = bitrev8(g[i]);
        return ascii_msb;
    }
    g = find_extra(cp);
    if (g)
        return g;
    g = ASCII['?' - 32];
    for (i = 0; i < 8; ++i)
        ascii_msb[i] = bitrev8(g[i]);
    return ascii_msb;
}
