static const unsigned char *ascii_glyph(char ch)
{
    /* Very small built-in subset for digits, Latin, punctuation used in paths. */
    static unsigned char buf[8];
    int i;
    memset(buf, 0, sizeof(buf));
    if (ch == ' ')
        return GLYPH_SPACE;
    if (ch >= '0' && ch <= '9') {
        /* stub digits as horizontal bars encoding value */
        buf[1] = 0x3C;
        buf[2] = (unsigned char)(0x20 | ((ch - '0') & 1));
        buf[3] = 0x3C;
        buf[4] = 0x04;
        buf[5] = 0x3C;
        return buf;
    }
    /* generic letter-like pattern from char code */
    for (i = 0; i < 8; ++i)
        buf[i] = (unsigned char)((0x5A ^ (unsigned)ch ^ (unsigned)(i * 17)) & 0x7E);
    buf[0] &= 0x3C;
    buf[7] = 0;
    return buf;
}

static const unsigned char *find_cyr(unsigned cp)
{
    size_t i;
    for (i = 0; i < sizeof(CYR) / sizeof(CYR[0]); ++i) {
        if (CYR[i].cp == cp)
            return CYR[i].rows;
    }
    return NULL;
}

static int utf8_next(const unsigned char **pp, unsigned *cp)
{
    const unsigned char *p = *pp;
    if (!*p)
        return 0;
    if (p[0] < 0x80) {
        *cp = p[0];
        *pp = p + 1;
        return 1;
    }
    if ((p[0] & 0xE0) == 0xC0 && p[1]) {
        *cp = ((p[0] & 0x1F) << 6) | (p[1] & 0x3F);
        *pp = p + 2;
        return 1;
    }
    if ((p[0] & 0xF0) == 0xE0 && p[1] && p[2]) {
        *cp = ((p[0] & 0x0F) << 12) | ((p[1] & 0x3F) << 6) | (p[2] & 0x3F);
        *pp = p + 3;
        return 1;
    }
    *cp = '?';
    *pp = p + 1;
    return 1;
}

