const unsigned char *shell_font_glyph(unsigned cp)
{
    const unsigned char *g;
    if (cp >= 32 && cp <= 126)
        return ASCII[cp - 32];
    g = find_cyr(cp);
    if (g)
        return g;
    return ascii_glyph('?');
}

int shell_font_utf8_draw(const char *utf8, int x, int y, ShellRgb c,
                         void (*plot)(int px, int py, ShellRgb col, void *ud), void *ud)
{
    const unsigned char *p = (const unsigned char *)utf8;
    unsigned cp;
    int cx = x;
    if (!utf8 || !plot)
        return 0;
    while (utf8_next(&p, &cp)) {
        const unsigned char *glyph = shell_font_glyph(cp);
        int gx, gy;
        for (gy = 0; gy < 8; ++gy) {
            unsigned char row = glyph[gy];
            for (gx = 0; gx < 8; ++gx) {
                if (row & (0x80 >> gx))
                    plot(cx + gx, y + gy, c, ud);
            }
        }
        cx += 8;
    }
    return cx - x;
}
